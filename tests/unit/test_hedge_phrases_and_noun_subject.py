@pytest.mark.unit
@pytest.mark.subsys_map
def test_set_as_an_opening_verb_is_not_ambiguous() -> None:
    charge, value, _modality, trace, _scope = classify_charge("Set NODE_ENV to production.")
    assert (charge, value) == ("IMPERATIVE", 1)
    assert "!amb" not in trace


@pytest.mark.unit
@pytest.mark.subsys_map
@pytest.mark.parametrize(
    ("text", "sign"),
    [
        ("It's best to avoid committing secrets.", -1),
        ("It's best to never push to main.", -1),
        ("It's best to not edit dist/ by hand.", -1),
        ("It is best to don't force-push.", -1),
        ("It's best to commit often.", 1),
    ],
)
def test_a_best_to_lead_before_a_prohibition_is_a_hedged_constraint(text: str, sign: int) -> None:
    assert best_to_sign(text) == sign
    charge, value, modality, _trace, _scope = classify_charge(text)
    assert (value, modality) == (sign, "hedged")
    assert charge == ("DIRECTIVE" if sign > 0 else "CONSTRAINT")
    atom = _atom(text, 0)
    _apply_hedged_should_floor([atom])
    assert (atom.charge_value, atom.modality) == (sign, "hedged")


