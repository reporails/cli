@pytest.mark.unit
@pytest.mark.subsys_map
@pytest.mark.parametrize(
    ("text", "hedged"),
    [
        ("Delete the temporary files wherever possible.", True),
        ("If possible, delete the temporary files.", True),
        ("Delete the temporary files (where possible).", True),
        ("Delete files where possible; keep the rest.", True),
        ("Check if possible duplicates exist before merging.", False),
        ("Check when possible conflicts arise.", False),
    ],
)
def test_possible_hedges_only_when_it_ends_the_clause(text: str, hedged: bool) -> None:
    assert hedges_with_possible(text) is hedged
    assert has_hedge_cue(text) is hedged
    assert (classify_charge(text)[2] == "hedged") is hedged


@pytest.mark.unit
@pytest.mark.subsys_map
@pytest.mark.parametrize(
    ("md", "plain", "hedged"),
    [
        ("Run `make where possible`", "Run make where possible", False),
        ("`It's best to` is a phrase we flag.", "It's best to is a phrase we flag.", False),
        ("Run `make build` where possible.", "Run make build where possible.", True),
        ("Run it **where possible**.", "Run it where possible.", True),
    ],
)
def test_the_lexical_entry_masks_code_spans_when_given_the_parsers_plain_text(
    md: str, plain: str, hedged: bool
) -> None:
    assert (classify_charge(md, plain_text=plain)[2] == "hedged") is hedged
    assert (classify_charge(md)[2] == "hedged") is hedged


@pytest.mark.unit
@pytest.mark.subsys_map
def test_the_hedge_floor_and_cue_read_the_markdown_that_keeps_its_code_spans() -> None:
    atom = _atom("Run `make where possible`.", 1)
    atom.plain_text = "Run make where possible."
    _apply_hedged_should_floor([atom])
    assert atom.modality == "imperative"
    assert has_hedge_cue("Run `make where possible`.") is False
    assert has_hedge_cue("Run it where possible.") is True


