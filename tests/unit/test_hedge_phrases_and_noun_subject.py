@pytest.mark.unit
@pytest.mark.subsys_map
@pytest.mark.parametrize(
    "text",
    [
        "Run `cleanup --where possible` before release.",
        "Run `make clean # if possible` before release.",
        "Run `cleanup --best` before release, it's fine.",
    ],
)
def test_a_hedge_phrase_inside_a_code_span_is_not_a_hedge(text: str) -> None:
    assert hedges_with_possible(text) is False
    assert classify_charge(text)[2] != "hedged"
    atom = _atom(text, 1)
    _apply_hedged_should_floor([atom])
    assert atom.modality == "imperative"


